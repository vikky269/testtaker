/* Generates docs/curriculum-coverage.md from the question banks: node tests/gen-docs.js */
const { load, DATA_FILES } = require('./load.js');
const fs = require('fs'), path = require('path');
const VA = load(DATA_FILES);
const L = [];
L.push('# Curriculum coverage', '', 'Generated by `node tests/gen-docs.js` from the question banks. Do not edit by hand.', '');
L.push('Frameworks: Pre-K uses the Head Start Early Learning Outcomes Framework (ELOF, 2015); Kindergarten and Grade 1 use the Common Core State Standards (CCSS) for Mathematics and for English Language Arts.', '');
for (const g of Object.keys(VA.GRADES)) {
  for (const s of ['math', 'ela']) {
    const bank = VA.QuestionBank.getBank(g, s);
    L.push('## ' + VA.GRADES[g].label + ' - ' + VA.SUBJECTS[s] + ' (' + bank.length + ' questions)', '');
    const byDomain = {};
    bank.forEach((q) => { (byDomain[q.domain] = byDomain[q.domain] || []).push(q); });
    L.push('| Domain | Questions | Standards (count) |', '|---|---|---|');
    Object.keys(byDomain).forEach((d) => {
      const c = {}; byDomain[d].forEach((q) => (c[q.standard] = (c[q.standard] || 0) + 1));
      L.push('| ' + d + ' | ' + byDomain[d].length + ' | ' + Object.keys(c).map((k) => k + ' (' + c[k] + ')').join(', ') + ' |');
    });
    L.push('', '| Standard | Text | Questions |', '|---|---|---|');
    const std = {}; bank.forEach((q) => (std[q.standard] = (std[q.standard] || []).concat(q.id)));
    Object.keys(std).forEach((k) => L.push('| ' + k + ' | ' + VA.STANDARDS[k].text.replace(/\|/g, '/') + ' | ' + std[k].join(', ') + ' |'));
    L.push('');
  }
}
fs.mkdirSync(path.join(__dirname, '..', 'docs'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'curriculum-coverage.md'), L.join('\n'));
console.log('wrote docs/curriculum-coverage.md (' + L.length + ' lines)');
